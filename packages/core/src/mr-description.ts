import type { ReviewItem } from './events.js';
import type { RunProjection } from './projection.js';

/**
 * Merge request title and description (§8.3). Rendered after every
 * iteration from the projection; the SCM adapters only transport it.
 */
export type ScmKind = 'gitlab' | 'github' | 'gitea';

export const GITHUB_TITLE_MAX = 72;

export function renderMrTitle(ticketKey: string, summary: string, scm: ScmKind): string {
  const title = `${ticketKey}: ${summary.trim()}`;
  if (scm !== 'github' || title.length <= GITHUB_TITLE_MAX) return title;
  return `${title.slice(0, GITHUB_TITLE_MAX - 1).trimEnd()}…`;
}

export interface MrDescriptionInput {
  ticket: { key: string; title: string; url: string | null };
  projection: RunProjection;
  runUrl: string;
  version: string;
  models: { implementer: string; reviewer: string };
}

function testsLine(it: RunProjection['iterations'][number]): string {
  const t = it.tests;
  if (!t) return 'tests not run';
  if (t.passed === null) return 'tests: result unparsed';
  const parts = [`${t.passed} passed`];
  if (t.failed) parts.push(`${t.failed} failed`);
  if (t.skipped) parts.push(`${t.skipped} skipped`);
  return `tests: ${parts.join(', ')}`;
}

function verdictLine(it: RunProjection['iterations'][number]): string {
  const v = it.verdict;
  if (!v) return 'no verdict yet';
  if (v.decision === 'approve') return 'approved';
  return `changes requested (${v.blocking.length} blocking, ${v.nonBlocking.length} non-blocking)`;
}

function item(i: ReviewItem): string {
  const where = i.file ? ` (\`${i.file}${i.line ? `:${i.line}` : ''}\`)` : '';
  return `**${i.id}** ${i.title}${where}${i.detail ? ` — ${i.detail}` : ''}`;
}

function money(usd: number): string {
  return `$${usd.toFixed(2)}`;
}

export function renderMrDescription(input: MrDescriptionInput): string {
  const p = input.projection;
  const last = p.lastVerdict;
  const lastAddressed = p.iterations.at(-1)?.addressed;
  const summary =
    last?.summary?.trim() || lastAddressed?.summary?.trim() || `Implements ${input.ticket.key}.`;
  const lines: string[] = [summary, ''];

  lines.push(
    '## Ticket',
    '',
    input.ticket.url
      ? `[${input.ticket.key}](${input.ticket.url}) — ${input.ticket.title}`
      : `${input.ticket.key} — ${input.ticket.title}`,
    '',
  );

  lines.push('## Changes per iteration', '');
  if (p.iterations.length === 0) lines.push('_No iteration has finished yet._');
  for (const it of p.iterations) {
    const files = it.pushed
      ? `${it.pushed.files_changed} files (+${it.pushed.additions} −${it.pushed.deletions})`
      : 'no push';
    lines.push(`- Iteration ${it.n}: ${files} · ${testsLine(it)} · ${verdictLine(it)}`);
  }
  lines.push('');

  const blockedAtCap = p.stage === 'blocked' && p.blockedReason === 'iteration_cap';
  if (blockedAtCap && last) {
    lines.push('## Unresolved review points', '');
    for (const b of last.blocking) lines.push(`- [ ] ${item(b)}`);
    lines.push('');
  }
  lines.push('## Review', '');
  const nits = last?.nonBlocking ?? [];
  if (nits.length === 0) lines.push(last ? '_No non-blocking items._' : '_No review yet._');
  for (const n of nits) lines.push(`- [ ] ${item(n)}`);
  lines.push('');

  const models = [...new Set([input.models.implementer, input.models.reviewer])].join(', ');
  lines.push(
    '## Run',
    '',
    `[Open in Mates](${input.runUrl}) · models: ${models} · cost: ${money(p.usage.costUsd)} · iterations: ${p.iteration}/${p.maxIterations}`,
    '',
  );
  lines.push(
    '---',
    `Generated by Mates ${input.version}. Reviewed by an AI reviewer; a human must review before merging.`,
  );
  return lines.join('\n');
}
