import { describe, expect, it } from 'vitest';
import { eventPayloadSchemas, type EventType, type RunEvent } from './events.js';
import type { z } from 'zod';
import { projectRun } from './projection.js';
import { renderMrDescription, renderMrTitle } from './mr-description.js';

function logOf(entries: Array<[EventType, unknown, string | null]>): RunEvent[] {
  let t = Date.UTC(2026, 9, 19, 14, 0, 0);
  return entries.map(([type, payload, inv], i) => {
    t += 60_000;
    return {
      id: i + 1,
      run_id: 'r',
      invocation_id: inv,
      ts: new Date(t).toISOString(),
      type,
      payload: (eventPayloadSchemas[type] as z.ZodType).parse(payload),
    } as RunEvent;
  });
}

const base: Array<[EventType, unknown, string | null]> = [
  ['run.created', { ticket_key: 'API-198', trigger: 'manual', by: 'ana', max_iterations: 4 }, null],
  ['invocation.scheduled', { mate: 'implementer', iteration: 1, job_name: 'i1', model: 'm' }, 'i1'],
  ['implementation.pushed', { commit: 'c', files_changed: 5, additions: 186, deletions: 31 }, 'i1'],
  [
    'implementation.tests',
    { passed: 142, failed: 0, skipped: 0, runner: 'vitest', duration_ms: 1, log_ref: null },
    'i1',
  ],
  [
    'usage.recorded',
    {
      model: 'm',
      input_tokens: 1,
      output_tokens: 1,
      cache_read_tokens: 0,
      cache_write_tokens: 0,
      cost_usd: 1.5,
    },
    'i1',
  ],
  ['invocation.scheduled', { mate: 'reviewer', iteration: 1, job_name: 'r1', model: 'm' }, 'r1'],
  [
    'review.verdict',
    {
      decision: 'changes_requested',
      blocking: [
        {
          id: 'B1',
          title: 'Backoff is unbounded',
          detail: 'no ceiling',
          file: 'src/retry.py',
          line: 14,
        },
      ],
      non_blocking: [{ id: 'N1', title: 'Docstring could mention the window', detail: '' }],
      summary: 'Ceiling missing.',
    },
    'r1',
  ],
];

describe('renderMrTitle', () => {
  it('truncates only for GitHub', () => {
    const long = 'A very long ticket summary that goes on and on past seventy-two characters';
    expect(renderMrTitle('API-198', long, 'gitlab')).toBe(`API-198: ${long}`);
    const gh = renderMrTitle('API-198', long, 'github');
    expect(gh.length).toBeLessThanOrEqual(72);
    expect(gh.endsWith('…')).toBe(true);
    expect(renderMrTitle('API-1', 'Short', 'github')).toBe('API-1: Short');
  });
});

describe('renderMrDescription', () => {
  const input = {
    ticket: {
      key: 'API-198',
      title: 'Retry policy for webhook delivery',
      url: 'https://jira/browse/API-198',
    },
    runUrl: 'https://mates/runs/r',
    version: '0.1.0',
    models: { implementer: 'claude-opus-5-5', reviewer: 'claude-opus-5-5' },
  };

  it('renders the §8.3 sections in order after a changes-requested verdict', () => {
    const md = renderMrDescription({ ...input, projection: projectRun(logOf(base)) });
    const order = [
      'Ceiling missing.',
      '## Ticket',
      '[API-198](https://jira/browse/API-198)',
      '## Changes per iteration',
      '- Iteration 1: 5 files (+186 −31) · tests: 142 passed · changes requested (1 blocking, 1 non-blocking)',
      '## Review',
      '- [ ] **N1** Docstring could mention the window',
      '## Run',
      '[Open in Mates](https://mates/runs/r) · models: claude-opus-5-5 · cost: $1.50 · iterations: 1/4',
      'Generated by Mates 0.1.0. Reviewed by an AI reviewer; a human must review before merging.',
    ];
    let pos = -1;
    for (const needle of order) {
      const next = md.indexOf(needle, pos + 1);
      expect(next, needle).toBeGreaterThan(pos);
      pos = next;
    }
    expect(md).not.toContain('Unresolved review points');
  });

  it('adds the unresolved points when blocked at the cap', () => {
    const events = logOf([
      ...base,
      ['run.stage_changed', { from: 'reviewing', to: 'blocked', reason: 'iteration_cap' }, null],
    ]);
    const md = renderMrDescription({ ...input, projection: projectRun(events) });
    expect(md).toContain(
      '## Unresolved review points\n\n- [ ] **B1** Backoff is unbounded (`src/retry.py:14`) — no ceiling',
    );
  });

  it('falls back to the implementer summary and placeholders before any review', () => {
    const events = logOf([
      base[0]!,
      base[1]!,
      base[2]!,
      [
        'implementation.addressed',
        { blocking_ids: [], skipped: [], summary: 'Cap retry attempts at five' },
        'i1',
      ],
    ]);
    const md = renderMrDescription({
      ...input,
      projection: projectRun(events),
      ticket: { ...input.ticket, url: null },
    });
    expect(md.startsWith('Cap retry attempts at five\n')).toBe(true);
    expect(md).toContain('API-198 — Retry policy for webhook delivery');
    expect(md).toContain('- Iteration 1: 5 files (+186 −31) · tests not run · no verdict yet');
    expect(md).toContain('_No review yet._');
  });
});
